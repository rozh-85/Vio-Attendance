export const TEXT: Record<PosLang, PosText> = { en, ku };

export function posErrorMessage(err: unknown, t: PosText = en): string {
  if (err instanceof DOMException && err.name === 'QuotaExceededError') return t.errors.STORAGE;
  if (!(err instanceof Error)) return t.errors.UNKNOWN;
  const code = 'code' in err ? String((err as { code: unknown }).code) : '';
  return t.errors[code] ?? (err.message || t.errors.UNKNOWN);
}

const LANG_KEY = 'vio.pos.lang';

export function readLang(): PosLang {
  try {
    return localStorage.getItem(LANG_KEY) === 'ku' ? 'ku' : 'en';
  } catch {
    return 'en';
  }
}

export function saveLang(lang: PosLang): void {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    // Storage blocked: the choice lasts until the page is closed.
  }
}
